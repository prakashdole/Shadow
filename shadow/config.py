"""Config — env vars and constants. No yaml, no pydantic."""

from __future__ import annotations

import os
from pathlib import Path

from dotenv import load_dotenv

ROOT = Path(__file__).resolve().parent.parent
load_dotenv(ROOT / ".env")

# --- model -----------------------------------------------------------
# brain.py dispatches on PROVIDER alone; nothing else in the codebase
# knows which model is in use.
#
#   nemotron  -> NVIDIA Nemotron 3 Super 120B on Bedrock, via boto3 Converse.
#                Needs AWS keys + a region that serves it (see below).
#   bedrock   -> Claude via Bedrock. Model ids take the `anthropic.` prefix.
#   anthropic -> Claude direct. Needs ANTHROPIC_API_KEY, bare model ids.
#   foundry   -> Claude via Microsoft. Needs FOUNDRY_ENDPOINT / FOUNDRY_API_KEY.
#
# Nemotron accepts temperature. Claude REJECTS temperature/top_p/top_k with
# a 400 — see _reply_claude() in brain.py.
PROVIDER = os.getenv("SHADOW_PROVIDER", "nemotron")
MODEL = os.getenv("SHADOW_MODEL", "nvidia.nemotron-super-3-120b")
# 0.9 made Nemotron ramble and then loop the same line until it hit the token
# cap. 0.6 still varies wording without degenerating.
TEMPERATURE = float(os.getenv("SHADOW_TEMPERATURE", "0.6"))
EFFORT = os.getenv("SHADOW_EFFORT", "low")   # Claude paths only

# A real reply is 4 short lines at most (typically a compact DM), so ~60
# tokens covers it. A generous cap is an invitation to ramble.
MAX_TOKENS = int(os.getenv("SHADOW_MAX_TOKENS", "80"))

# Regions that serve Nemotron 3 Super 120B. ap-south-1 (Mumbai) is NOT one
# of them and there is no global cross-region routing, so the closest option
# to India is ap-northeast-1 (Tokyo).
NEMOTRON_REGIONS = {
    "us-east-1", "us-east-2", "us-west-2",
    "eu-south-1", "eu-west-1", "eu-west-2",
    "ap-northeast-1", "ap-southeast-2", "ap-southeast-4",
    "sa-east-1", "us-gov-west-1",
}
# Verified working 2026-07-26. ap-northeast-1 (Tokyo) is listed as supported by
# AWS but read-timed-out at 25s with this key — probably key/region scoping.
NEMOTRON_DEFAULT_REGION = "us-east-1"

# Fail fast instead of hanging. A hung Bedrock call is how Tokyo presented.
CONNECT_TIMEOUT = 10
READ_TIMEOUT = 60

_env_region = os.getenv("AWS_REGION", "")
if PROVIDER == "nemotron" and _env_region not in NEMOTRON_REGIONS:
    AWS_REGION = os.getenv("SHADOW_AWS_REGION", NEMOTRON_DEFAULT_REGION)
else:
    AWS_REGION = _env_region or "us-east-1"

FOUNDRY_ENDPOINT = os.getenv("FOUNDRY_ENDPOINT", "")

# --- paths -----------------------------------------------------------
DATA_DIR = ROOT / "data"
PEOPLE_DIR = DATA_DIR / "people"
VOICE_FILE = ROOT / "voice.json"        # generated by build_voice.py
PERSONALITY_FILE = ROOT / "personality.md"   # legacy prose, no longer prompted
STATE_FILE = ROOT / ".shadow_state.json"
LOG_FILE = ROOT / "shadow.log"

# --- browser ---------------------------------------------------------
CDP_URL = os.getenv("SHADOW_CDP_URL", "http://localhost:9222")
IG_INBOX = "https://www.instagram.com/direct/inbox/"
IG_THREAD = "https://www.instagram.com/direct/t/{thread_id}/"
IG_HOME = "https://www.instagram.com/"
IG_STORY = "https://www.instagram.com/stories/{username}/"

# --- pacing ----------------------------------------------------------
ACTIVE_START, ACTIVE_END = 9, 23   # local hours, inclusive start / exclusive end
WORDS_PER_SEC = 0.5                # typing pause before send
GAP_BETWEEN_THREADS = (20, 60)     # seconds
GAP_BETWEEN_CYCLES = (30, 90)
HISTORY_LIMIT = 40                 # stored messages fed to the model
STORIES_PER_DAY = 5

# How many messages to pull off the screen per thread. Instagram renders only
# ~10 at a time and loads more on a real wheel event, so anything above ~10
# costs one scroll round (~1s). 20 gives the model enough context to follow a
# conversation without paying for deep history it will not use.
READ_DEPTH = 20

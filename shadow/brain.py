"""Brain — one model call per reply. One model, no fallbacks.

Default: NVIDIA Nemotron 3 Super 120B on AWS Bedrock, via the Converse API
(sigv4 with plain AWS keys — no extra SDK, no separate Bedrock API key).

Nemotron differs from Claude in three ways that shape this file:
  - temperature IS accepted (Claude 400s on it). Used for voice variety.
  - no server-side JSON schema, so output is one message per line and
    parsed here. Simpler than a schema; nothing to go wrong but blank lines.
  - no prompt caching (cache_control is Anthropic-only), so the ~5KB voice
    prompt is resent every call. Cheap enough at Nemotron pricing.

Nemotron is a hybrid reasoning model and may wrap reasoning in <think> tags;
those are stripped before parsing.

The Claude path is kept behind PROVIDER for a swap without a rewrite.
"""

from __future__ import annotations

import json
import logging
import re
from dataclasses import dataclass

from shadow.config import (
    AWS_REGION, CONNECT_TIMEOUT, EFFORT, FOUNDRY_ENDPOINT, MAX_TOKENS, MODEL,
    PROVIDER, READ_TIMEOUT, TEMPERATURE, VOICE_FILE,
)
from shadow.memory import Msg

log = logging.getLogger("shadow.brain")

# Freeze list — topics the bot must not answer alone. Keyword scan only,
# no second model call. A hit means skip the thread and log it.
FREEZE = {
    "money": ["lend", "borrow", "upi", "transfer", "loan", "paytm", "gpay",
              "paise", "rupee", "send money", "need money", "broke"],
    "emergency": ["hospital", "accident", "emergency", "died", "death",
                  "funeral", "ambulance", "icu", "critical", "urgent help"],
    "emotional": ["depressed", "depression", "suicide", "suicidal", "anxiety",
                  "mental health", "breakup", "break up", "hopeless",
                  "rona aa raha", "bahut bura", "nahi rehna"],
    "confession": ["i love you", "i like you", "feelings for you", "propose",
                   "confession", "pyaar", "mohabbat", "crush"],
    "meeting": ["come over", "plans for", "this weekend", "party tonight",
                "milte hain", "aa jao", "kab miloge"],
}

# Used to name this person's actual swear words in the prompt, rather than
# stating a bare percentage the model then ignores. Also imported by
# eval_voice.py so measurement and instruction use the same list.
_SWEAR_RE = re.compile(
    r"\b(bhosad\w*|madarchod|laudi|randi|bhadva|bhadve|chutiya|gaand|sale|"
    r"saale|mkc|bkl|bc|bsdk|wtf|fuck\w*|shit\w*|bitch|harami|kutta|kamina|"
    r"ghewar)\b", re.I)

SKIP_TOKEN = "NOREPLY"
_THINK = re.compile(r"<think>.*?</think>", re.S | re.I)
_LEAD = re.compile(r"^\s*(?:[-*>]|\d+[.)])\s*")   # bullets / numbering
_QUOTED = re.compile(r'^["\'](.*)["\']$')


@dataclass
class Decision:
    action: str            # "reply" | "skip" | "freeze"
    messages: list[str]
    note: str = ""


def frozen(text: str) -> str | None:
    """Return the freeze category if this message hits the list, else None."""
    low = text.lower()
    for cat, words in FREEZE.items():
        if any(w in low for w in words):
            return cat
    return None


_VOICE: dict | None = None


def voice() -> dict:
    """Load voice.json once. Generated by build_voice.py from the real corpus."""
    global _VOICE
    if _VOICE is None:
        if not VOICE_FILE.exists():
            raise RuntimeError(
                f"{VOICE_FILE.name} missing. Run: python build_voice.py"
            )
        _VOICE = json.loads(VOICE_FILE.read_text(encoding="utf-8"))
    return _VOICE


def reload_voice() -> None:
    global _VOICE
    _VOICE = None


def _register(person: str, prof: dict) -> tuple[dict | None, str]:
    """Find this person's measured register in voice.json.

    Returns (entry, matched_key). Instagram display names do not always match
    the imported folder name, so fall back the same way memory.resolve does.
    """
    people = voice().get("people", {})
    if person in people:
        return people[person], person
    low = person.lower()
    for k, v in people.items():
        if k.lower() == low or (v.get("display_name", "").lower() == low):
            return v, k
    for k in people:
        if low in k.lower() or k.lower() in low:
            return people[k], k
    return None, ""


def _system(person: str, prof: dict, hide: str | None = None) -> str:
    """Build the system prompt: measured global voice + this person's register.

    Only the one relevant person is included, never all 23 — the whole point of
    voice.json is that the model reads a compact spec instead of raw chat logs.

    `hide` drops any few-shot example whose incoming message matches it. Only
    eval_voice.py uses this: without it a held-out case is still sitting in the
    prompt with its answer attached, and the model "copies" what it was handed.
    """
    v = voice()
    entry, key = _register(person, prof)

    ident = v["identity"]
    gs = v["global_style"]
    burst = v["burst_behaviour"]
    vocab = v["vocabulary"]

    close = (entry or {}).get("closeness") or prof.get("closeness", 5)
    rel = (entry or {}).get("relationship") or prof.get("relationship") or "unknown"
    notes = ((entry or {}).get("notes") or prof.get("context") or "").strip()

    # Per-person numbers when they exist, global otherwise. These are measured
    # from real messages to this person, so they beat any tier heuristic.
    st = (entry or {}).get("style") or gs
    ex = (entry or {}).get("examples") or v["examples_global"][:6]
    if hide:
        h = hide.strip().lower()
        ex = [e for e in ex if e["them"].strip().lower() != h]
    top_words = (entry or {}).get("my_top_words") or vocab["slang_and_hinglish"][:12]
    emo = (entry or {}).get("my_emoji") or [e["emoji"] for e in vocab["emoji_ranked"][:4]]

    spec = {
        "you_are": ident,
        "how_you_write_overall": gs,
        "messages_per_turn": {
            "mean": burst["mean_messages_per_turn"],
            "pct_single_message": burst["pct_single_message"],
            "pct_two_or_three": burst["pct_two_or_three"],
            "pct_four_plus": burst["pct_four_plus"],
        },
        "your_words": vocab["slang_and_hinglish"],
        "your_openers": [o["word"] for o in vocab["top_openers"]],
        "your_short_replies": [o["text"] for o in vocab["common_short_replies"]],
        "replying_to": {
            "name": (entry or {}).get("display_name") or person,
            "relationship": rel,
            "closeness_out_of_10": close,
            "notes": notes,
            "measured_style_with_this_person": st,
            "words_you_use_with_them": top_words,
            "emoji_you_use_with_them": emo,
        },
    }

    examples = "\n\n".join(
        "them: " + e["them"] + "\n" + "\n".join("you: " + m for m in e["me"])
        for e in ex
    )

    return f"""Draft a natural Instagram DM using the account owner's supplied writing preferences.

This JSON is your measured writing style, computed from {gs['messages_counted']} of your real messages. The percentages are how you actually write - match them.

{json.dumps(spec, ensure_ascii=False, indent=1)}

# Real examples of you replying to this person

These are examples supplied by the owner. Copy this register - the length, the capitalisation, the language mix, the sloppiness.

{examples}

# How to reply

Respond with ONLY a JSON array of message strings. Nothing before it, nothing after it. No explanation, no labels, no transcript.

["yea"]
["nahi bhai", "kal dekhta hu"]
["{SKIP_TOKEN}"]

Say something real. This matters more than being short. Answer the actual question, react to the actual thing they said, or ask them something back. A bare "wow" or "ha" is only a real reply when there is genuinely nothing to respond to - if they asked you something, told you news, or made a joke, you engage with it.

Never repeat their message back at them. That is not a reply. Do not echo their words with a question mark added ("If time permits." -> "If time permits?" is wrong). If you did not understand them, use your own words: "matlab", "kya", "huh", "kya bol raha hai".

Aim for around {gs['median_chars']} characters - a short clause, not a sentence, but not a grunt either. "ha bhai", "yea", "wow" alone are filler and are almost never the whole reply. Name the thing, ask the specific question, or give the actual answer. If your reply is under 8 characters, you have probably said nothing.

You double-text constantly. Two messages is normal - say the thing, then add the follow-up thought or the question on its own line. Look at the examples above: most of them are two or three messages. Three happens, four never.

Do not invent events. If you do not know how something went, ask or deflect - do not make up news about yourself.

Mirror their language. About half your messages are plain English and half are Hinglish - you are not forcing Hindi into every reply. If they write English, reply in English. If they write Hindi or Hinglish, reply in Hinglish. Never Devanagari script - Hindi is always written in Latin letters.

Do not clean up your writing. No full stops at the end ({gs['pct_ends_with_period']}% have one). Apostrophes are rare ({gs['pct_with_apostrophe']}%). Typos stay.

Your emoji are {' '.join(emo)} and you lean on them a lot with this person ({st.get('pct_with_emoji', 14)}% of messages). Anything funny, absurd, painful or relatable gets {emo[0] * 3 if emo else '🤣🤣🤣'} as an entire message with no words at all - that is a complete, normal reply for you. Also fine tacked onto the end of a line. Only use the ones listed; never a smiley or emoji you do not use.

You swear with this person in {st.get('pct_with_swear', 0)}% of your messages - words like {', '.join(w for w in top_words if _SWEAR_RE.search(w)) or 'sale, bhadve, bkl'}. It is not aggression, it is how you talk to them. Do not sanitise yourself, and do not add swearing where the rate is near zero.

If nothing needs a reply - they reacted to something, or the conversation is finished - return exactly ["{SKIP_TOKEN}"].

Never write a paragraph. Never greet formally. Never explain what they already know."""


def _fmt(person: str, msgs: list[Msg]) -> str:
    return "\n".join(
        f"{'You' if m.sender == 'me' else person}: {m.content}" for m in msgs
    )


def _user(person: str, past: list[Msg], live: list[Msg]) -> str:
    """Old history and the current screen are labelled separately.

    Glued together they read as one continuous conversation, and the model
    answers whatever text sits nearest the end — which is how it started
    parroting stale lines out of the imported history.
    """
    parts = []
    if past:
        parts.append(
            "# Earlier chat history with this person (context only, already "
            "happened, do NOT reply to any of this)\n\n" + _fmt(person, past)
        )
    parts.append(
        "# On screen right now - this is what you are replying to\n\n"
        + _fmt(person, live)
    )
    parts.append(
        f"Reply to {person}'s last message. JSON array only."
    )
    return "\n\n".join(parts)


# Meta-text the model sometimes emits instead of just replying: headers it
# invents, or narration about what it is doing. Any line matching this is
# scaffolding, not a message, and everything from there on is discarded.
_META = re.compile(
    r"^(?:"
    r"(?:based on|according to|given) the\b"
    r"|(?:here (?:is|are)|this is) (?:my|the|a)\b"
    r"|your turn\b|my turn\b|reply:|response:|answer:|output:|note:"
    r"|the (?:style|analysis|profile|register|examples?)\b"
    r"|(?:style|voice) analysis\b"
    r"|them:|you:|me:"
    r"|[A-Z][A-Z ]{6,}:"          # invented ALLCAPS headers e.g. "MESSAGES STATION:"
    r")",
    re.I,
)


_ARRAY = re.compile(r"\[.*?\]", re.S)

# Smart quotes and ellipsis the model sometimes emits inside a JSON array,
# which make it unparseable. Normalised before the parse attempt.
_SMART = {"“": '"', "”": '"', "‘": "'", "’": "'",
          "…": "...", "«": '"', "»": '"'}

# Debris from a half-written JSON array leaking into a message: stray brackets
# with quotes, orphan quote-comma, or a run of non-ASCII that is not emoji
# (mojibake). A message containing any of this is not something to send.
_DEBRIS = re.compile(
    r'\["|"\]|",\s*"|^\s*[\[\]]|[\[\]]\s*$|\.{4,}|["“”]\s*$'
)


def _sane(line: str) -> bool:
    """False if the line looks like parser debris rather than a message."""
    if _DEBRIS.search(line):
        return False
    # letters that are neither ASCII nor emoji nor Devanagari => mojibake
    odd = sum(1 for c in line
              if not c.isascii() and c.isalpha() and not 0x900 <= ord(c) <= 0x97F)
    return odd <= 2


def _norm(s: str) -> str:
    """Strip punctuation and case so echo detection survives 'X.' -> 'X?'."""
    return re.sub(r"[^\w\s]", "", s.lower()).strip()


def _clean(lines: list[str], their: str = "") -> list[str]:
    """Drop scaffolding and echoes, de-loop, cap at 4. Shared by both paths."""
    out: list[str] = []
    seen: set[str] = set()
    theirs = _norm(their)
    for raw in lines:
        line = _LEAD.sub("", str(raw)).strip()
        if not line:
            continue
        if line.upper().strip(".!") == SKIP_TOKEN:
            return []
        if _META.match(line):
            break                       # scaffolding: drop it and everything after
        m = _QUOTED.match(line)
        if m:
            line = m.group(1).strip()
        if not line:
            continue
        # Parroting their message back, with or without an added "?", is not a
        # reply. The model does this when it does not understand them.
        if theirs and _norm(line) == theirs:
            continue
        # Half-parsed JSON debris must never reach a real DM.
        if not _sane(line):
            continue
        key = line.lower().rstrip(".!?")
        if key in seen:
            break                       # started looping; keep what came before
        seen.add(key)
        out.append(line)
        if len(out) == 4:
            break
    return out


def _parse(text: str, their: str = "") -> list[str]:
    """Nemotron output -> list of messages. [] means skip.

    A JSON array is requested because it gives the model a place to stop.
    Asking for one-message-per-line has no terminator, so it kept filling
    tokens until maxTokens and then looped the same line.

    `their` is the message being replied to, so an echo of it can be dropped.
    Falls back to line parsing when the array is missing or malformed.
    """
    text = _THINK.sub("", text).strip()
    if not text:
        return []
    if text.upper().strip(".!") == SKIP_TOKEN:
        return []

    # Smart quotes break json.loads, which sent the whole reply down the line
    # fallback and leaked '["Yea bhai",…' style debris into messages.
    for bad, good in _SMART.items():
        text = text.replace(bad, good)

    m = _ARRAY.search(text)
    if m:
        try:
            data = json.loads(m.group(0))
            if isinstance(data, list):
                return _clean([x for x in data if isinstance(x, str)], their)
        except json.JSONDecodeError:
            pass                        # fall through to line parsing

    return _clean(text.splitlines(), their)


# --- provider paths ---------------------------------------------------

def _reply_nemotron(system: str, user: str) -> tuple[str, dict]:
    """Bedrock Converse. Returns (text, usage).

    Auth is the AWS_BEARER_TOKEN_BEDROCK long-term API key, which boto3 picks
    up from the environment on its own. The older AKIA sigv4 keys in .env
    return 401 and are unused.
    """
    import boto3
    from botocore.config import Config

    client = boto3.client(
        "bedrock-runtime",
        region_name=AWS_REGION,
        # Fail fast. An unscoped region hangs rather than erroring.
        config=Config(
            connect_timeout=CONNECT_TIMEOUT,
            read_timeout=READ_TIMEOUT,
            retries={"max_attempts": 2},
        ),
    )
    resp = client.converse(
        modelId=MODEL,
        system=[{"text": system}],
        messages=[{"role": "user", "content": [{"text": user}]}],
        # Nemotron rejects stopSequences ("This model doesn't support the
        # stopSequences field"), so runaway generation is bounded by a tight
        # maxTokens and cleaned up by _parse() instead.
        inferenceConfig={"maxTokens": MAX_TOKENS, "temperature": TEMPERATURE},
    )
    blocks = resp["output"]["message"]["content"]
    text = "".join(b.get("text", "") for b in blocks)
    u = resp.get("usage", {})
    return text, {
        "in": u.get("inputTokens"),
        "out": u.get("outputTokens"),
        "stop": resp.get("stopReason"),
    }


def _reply_claude(system: str, user: str) -> tuple[str, dict]:
    """Anthropic path — cached system block, schema-enforced output.
    NOTE: never pass temperature/top_p/top_k here; Claude 400s on them."""
    if PROVIDER == "bedrock":
        from anthropic import AnthropicBedrockMantle
        client = AnthropicBedrockMantle(aws_region=AWS_REGION)
    elif PROVIDER == "anthropic":
        from anthropic import Anthropic
        client = Anthropic()
    else:  # foundry
        import os

        from anthropic import AnthropicFoundry
        client = AnthropicFoundry(
            api_key=os.environ["FOUNDRY_API_KEY"], base_url=FOUNDRY_ENDPOINT,
        )

    schema = {
        "type": "object",
        "properties": {
            "messages": {"type": "array", "items": {"type": "string"}},
            "action": {"type": "string", "enum": ["reply", "skip"]},
        },
        "required": ["messages", "action"],
        "additionalProperties": False,
    }

    resp = client.messages.create(
        model=MODEL,
        max_tokens=MAX_TOKENS,
        system=[{"type": "text", "text": system,
                 "cache_control": {"type": "ephemeral"}}],
        thinking={"type": "disabled"},
        output_config={"effort": EFFORT,
                       "format": {"type": "json_schema", "schema": schema}},
        messages=[{"role": "user", "content": user}],
    )
    u = resp.usage
    usage = {"in": u.input_tokens, "out": u.output_tokens,
             "cache_r": u.cache_read_input_tokens}
    if resp.stop_reason == "refusal":
        return SKIP_TOKEN, usage

    raw = next((b.text for b in resp.content if b.type == "text"), "")
    data = json.loads(raw)
    if data.get("action") != "reply":
        return SKIP_TOKEN, usage
    return "\n".join(data.get("messages", [])), usage


def reply(
    person: str,
    prof: dict,
    live: list[Msg],
    past: list[Msg] | None = None,
    hide_example: str | None = None,
) -> Decision:
    """One model call. Returns a Decision. Never raises on model content.

    `live` is what is on screen now — the model replies to its last message.
    `past` is stored history, passed as labelled context only.
    `hide_example` drops a matching few-shot example; eval_voice.py only.
    """
    if not live:
        return Decision("skip", [], "empty conversation")

    cat = frozen(live[-1].content)
    if cat:
        log.warning("FREEZE [%s] %s: %r", cat, person, live[-1].content[:120])
        return Decision("freeze", [], cat)

    if not PROVIDER or not MODEL:
        raise RuntimeError(
            "No model configured. Set SHADOW_PROVIDER and SHADOW_MODEL in .env.\n"
            "  nemotron  -> AWS keys + a region that serves it (see config.py)\n"
            "  bedrock   -> AWS keys, Claude via Bedrock\n"
            "  anthropic -> ANTHROPIC_API_KEY\n"
            "  foundry   -> FOUNDRY_ENDPOINT / FOUNDRY_API_KEY"
        )

    # Drop any stored line that is also on screen, so the model does not see
    # the same message twice under two different headings.
    on_screen = {(m.sender, m.content) for m in live}
    ctx = [m for m in (past or []) if (m.sender, m.content) not in on_screen]

    system = _system(person, prof, hide=hide_example)
    user = _user(person, ctx, live)

    if PROVIDER == "nemotron":
        text, usage = _reply_nemotron(system, user)
    elif PROVIDER in ("bedrock", "anthropic", "foundry"):
        text, usage = _reply_claude(system, user)
    else:
        raise RuntimeError(
            f"Unknown SHADOW_PROVIDER {PROVIDER!r}: "
            "use nemotron, bedrock, anthropic, or foundry"
        )

    log.info("model %s tokens=%s", MODEL, usage)

    msgs = _parse(text, their=live[-1].content)
    if not msgs:
        return Decision("skip", [], "model chose skip")
    return Decision("reply", msgs)
